type Key = keyof (typeof STRINGS)['en'];

const language = (): keyof typeof STRINGS => {
  const lang = (
    window.mainConfig?.get('options.language') ??
    document.documentElement.lang ??
    navigator.language
  ).toLowerCase();
  return lang.startsWith('zh') ? 'zh-TW' : 'en';
};

export const s = (key: Key, name?: string): string => {
  const text: string = STRINGS[language()][key];
  return name === undefined ? text : text.replace('{name}', name);
};
